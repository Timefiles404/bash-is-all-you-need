// ---------------------------------------------------------------------------
// ANSI 转义序列扫描
// ---------------------------------------------------------------------------

// ansiLen 返回从 s[i] 开始那段转义序列的字节长度；那里没有转义序列就返回
// 0。
//
// 这是本文件的承重件：下面的每个函数都是"走一遍字符串，ansiLen 说跳多少就
// 跳多少，剩下的量宽度"。它必须是一个真正的扫描器，不能是正则，也不能是
// "到字母了没"的循环，因为终端输出里真会出现的那两种形式，结束方式不一样：
//
//	CSI  ESC [  0x30-0x3f*  0x20-0x2f*  0x40-0x7e     ← 颜色、光标移动
//	OSC  ESC ]  ...         BEL | ESC \               ← 窗口标题、超链接
//
// 咬人的是 OSC。OSC-8 超链接里嵌着一个 URL，而 URL 全是字母——遇到第一个字
// 母就停的扫描器，只吃掉 "ESC ]8;;h" 这四个字节，然后把
// "ttps://example.com" 当成可见文本来量，于是表里每个带超链接的格子都宽出
// 十八列。
//
// 被截断的或者格式不对的序列，会把字符串剩下的部分全吞掉。这是有意的：另
// 一条路是把尾巴当可见文本吐出去，而半截转义序列照字面打出来，会把它之后
// 的每一行都搞坏。
//
// exec.go 的 sanitize() 用正则认同一套语法，在那边这就是对的工具：它一趟就
// 把一整块里的转义序列全剥掉，因为发给模型的工具输出根本不该带颜色。这里
// 要的是相反的形状——给定偏移量处那段序列的**长度**——好让这趟走查一路累
// 加列数。这个问题正则答不上来，除非每碰一个 rune 就从头再扫一遍。
func ansiLen(s string, i int) int {
	if i >= len(s) || s[i] != esc {
		return 0
	}
	if i+1 >= len(s) {
		return 1 // 末尾孤零零一个 ESC：没有宽度，也没有内容
	}
	switch s[i+1] {
	case '[': // CSI
		j := i + 2
		for j < len(s) && s[j] >= 0x30 && s[j] <= 0x3f {
			j++ // 参数字节：数字、';'，以及私有用途标记
		}
		for j < len(s) && s[j] >= 0x20 && s[j] <= 0x2f {
			j++ // 中间字节
		}
		if j < len(s) && s[j] >= 0x40 && s[j] <= 0x7e {
			return j + 1 - i // 结束字节：'m' 是 SGR，'H'/'J'/'K'/… 是其余那些
		}
		return len(s) - i
	case ']': // OSC
		for j := i + 2; j < len(s); j++ {
			if s[j] == 0x07 {
				return j + 1 - i // BEL 终止符
			}
			if s[j] == esc && j+1 < len(s) && s[j+1] == '\\' {
				return j + 2 - i // ST 终止符
			}
		}
		return len(s) - i
	default:
		// 两字节的转义：ESC M（反向索引）、ESC 7 / ESC 8（保存和恢复光
		// 标）、ESC ( B（字符集选择——三个字节，这一个我们就是差了一）。
		// 它们都不带宽度，也都不会出现在 TUI 要量的字符串里，所以答二是
		// 务实的答案，不是正确的答案；这段注释就是收据。
		return 2
	}
}

// isSGR 报告 seq 是不是颜色/属性序列，以及它是不是一个 reset。
//
// 这个区分要紧，是因为只有 SGR 带着比序列本身活得更久的状态。光标移动是一
// 次事件；颜色是一种**模式**，而你切断字符串时还开着的模式，会漏到之后打
// 印的一切东西上——包括你的程序退出之后的 shell 提示符，用户就是这样得到
// 一个永远红着的终端，还不知道是哪个程序干的。
//
// "reset" 指的是参数为空或者全为零的 SGR：\x1b[m、\x1b[0m、\x1b[00m。其余
// 一律算开启状态，包括 \x1b[39m（默认前景色）——它其实真的会清掉颜色。这
// 样偏在多关一次那一边，而多余的 \x1b[0m 看不出来，少一个可看得出来。
func isSGR(seq string) (sgr, reset bool) {
	if len(seq) < 3 || seq[0] != esc || seq[1] != '[' || seq[len(seq)-1] != 'm' {
		return false, false
	}
	for _, p := range strings.Split(seq[2:len(seq)-1], ";") {
		if strings.Trim(p, "0") != "" {
			return true, false
		}
	}
	return true, true
}

// ---------------------------------------------------------------------------
// dispWidth
// ---------------------------------------------------------------------------

// dispWidth 返回 s 的显示宽度，单位是终端的列，跳过其中所有 ANSI 转义序
// 列。
//
// 非法 UTF-8 会一个字节一个字节地解成 U+FFFD，每个坏字节算一列——终端就是
// 这么画它的。这样一来，损坏的字节不会悄悄把某一列缩掉，而是明明白白地弄
// 出一团糟；布局要是把坏输入不声不响地吸收了，那就是在把它藏起来。
func dispWidth(s string) int {
	w := 0
	for i := 0; i < len(s); {
		if n := ansiLen(s, i); n > 0 {
			i += n
			continue
		}
		r, size := utf8.DecodeRuneInString(s[i:])
		w += runeWidth(r)
		i += size
	}
	return w
}

