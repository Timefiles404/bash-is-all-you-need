// truncCols 返回 s 的一个前缀，最多占 n 列。它绝不会在 ANSI 转义序列中间下
// 刀，也绝不会把终端留在带颜色的状态里：切的位置上要是还有 SGR 序列开着，
// 它会补上 "\x1b[0m"。转义序列不计入 n。
//
// 它要防的是两种失败，而 s[:n] 两种都会产生：
//
//  1. 在 "\x1b[31m" 中间切一刀，输出里就留下 "\x1b[3"。终端会把你接下来打
//     的那个字符当成这段序列缺的结束字节，一口吃掉。少一个字母，几行之
//     后，来自程序里完全不相干的另一处。
//
//  2. 在多字节 rune 中间切一刀，会吐出半个汉字——一个谁也说不准宽度的替换
//     字形，从此这一行剩下的列数全对不上了。
//
// 有意思的是宽字符边界这种情况。要是只剩一列，而下一个 rune 要两列，我们
// 就停在它前面，用一个空格把这落单的一列补上。返回 n-1 列跟返回 n+1 列一
// 样糟：格子少一列，跟多一列一样会把表格错开；而调用方看见截断器写"最多 n
// 列"，只要它真截了，就有理由读成"正好 n 列"。
func truncCols(s string, n int) string {
	if n <= 0 {
		return ""
	}
	var b strings.Builder
	w, open, cut := 0, false, false
	for i := 0; i < len(s); {
		if l := ansiLen(s, i); l > 0 {
			seq := s[i : i+l]
			b.WriteString(seq)
			if sgr, reset := isSGR(seq); sgr {
				open = !reset
			}
			i += l
			continue
		}
		r, size := utf8.DecodeRuneInString(s[i:])
		rw := runeWidth(r)
		if w+rw > n {
			cut = true
			break
		}
		b.WriteString(s[i : i+size]) // 照抄字节；绝不重新编码这个 rune
		w += rw
		i += size
	}
	// 先关颜色，再补空格，不能反过来。背景色还开着就补空格，会在空缺处画出
	// 一整块颜色，而这正是让截断过的格子看起来像渲染 bug 的那种痕迹。
	if open {
		b.WriteString(sgrReset)
	}
	// 只有真的提前停下来了才补。短字符串原样放着——补它是 padCols 的活儿，
	// 两件事混在一起会让 truncCols 变得出人意料。这里 n-w 永远正好是 1（唯
	// 一能带着 w < n 跳出循环的情形是 rw == 2 且 n-w == 1），但写成通式能
	// 让这一点看得见。
	if cut && w < n {
		b.WriteString(strings.Repeat(" ", n-w))
	}
	return b.String()
}

// ---------------------------------------------------------------------------
// padCols
// ---------------------------------------------------------------------------

// padCols 用空格把 s 补到正好 n 个显示列；s 更宽的话就（经由 truncCols）
// 截断。
//
// 注意它跟 truncCols 的不对称：s 装得下的时候，就算 s 留着一个没关的 SGR，
// padCols 也**不会**补 reset。什么都没切，就什么都没坏；调用方在这个格子里
// 开颜色、在下个格子里关掉，是完全正当的做法，一个"好心"的 reset 会不声不
// 响地把它毁掉。代价是：给一个背景色还开着的字符串补空格，补出来的是带颜
// 色的空格——那是调用方自己的颜色，忠实地照做而已。
func padCols(s string, n int) string {
	w := dispWidth(s)
	switch {
	case w == n:
		return s
	case w > n:
		return truncCols(s, n)
	case n <= 0:
		// n 是负数而 s 是空的：走到 truncCols 去，而不是把一个负数递给
		// strings.Repeat，在重绘中间 panic。
		return truncCols(s, n)
	}
	return s + strings.Repeat(" ", n-w)
}

// ---------------------------------------------------------------------------
// wrapCols
// ---------------------------------------------------------------------------

// wrapCols 把 s 硬折成一行行，每行最多 n 列。它认得 ANSI：绝不切开转义序列
// 或者多字节 rune，并且在每一条续行的开头，把当前生效的 SGR 状态重新打开。
//
// 是硬折，不是按词折，而对它要干的活儿来说这才是对的默认：固定窗格里的命
// 令输出和模型文本，那里一个长得断不开的 token——一条路径、一坨 base64、一
// 帧栈——绝不能被允许把布局撑得比它所在的窗格还宽。
//
// 每行都把颜色重新打开一遍，不是为了好看。终端不会让 SGR 状态跨过一行别人
// 可能重绘的行：只要另一个窗格、一次滚动或者一次重绘落在这两行之间，没重
// 新打开的颜色从第二行起就没了。在每行开头把状态发一遍，每一行才各自成
// 立，而这也正是调用方能单独滚动、重排、重打任意一行的原因。
//
// 嵌在里面的 "\n" 强制断行，因为把裸换行写进固定窗格，就是逃出了窗格。颜
// 色状态能跨过它活下来。
func wrapCols(s string, n int) []string {
	if n <= 0 {
		// 零宽的窗格什么也装不下。nil 是诚实的答案，更要紧的是，它是会停下
		// 来的那个答案——否则下面那个循环会没完没了地吐空行。
		return nil
	}
	var (
		lines []string
		cur   strings.Builder
		w     int
		state []string // 当前生效的 SGR 序列，按见到的顺序排
	)
	// 这里攒的是整段整段的 SGR 序列，而不是把它们解析进一个个属性槽。
	// "\x1b[31m\x1b[32m" 会把两段都重发一遍，让终端按它当初的方式去裁决——
	// 后来者赢。把九个属性分别建模，代码更多，而对 TUI 会发出的任何东西来
	// 说并不更正确。
	start := func() {
		cur.Reset()
		w = 0
		for _, seq := range state {
			cur.WriteString(seq)
		}
	}
	end := func() string {
		if len(state) > 0 {
			cur.WriteString(sgrReset)
		}
		return cur.String()
	}
	start()
	for i := 0; i < len(s); {
		if l := ansiLen(s, i); l > 0 {
			seq := s[i : i+l]
			cur.WriteString(seq)
			if sgr, reset := isSGR(seq); sgr {
				if reset {
					state = state[:0]
				} else {
					state = append(state, seq)
				}
			}
			i += l
			continue
		}
		r, size := utf8.DecodeRuneInString(s[i:])
		if r == '\n' {
			lines = append(lines, end())
			start()
			i += size
			continue
		}
		rw := runeWidth(r)
		if w+rw > n {
			if w == 0 {
				// 这个 rune 比整个窗格还宽：n == 1，碰上一个汉字。它永远装
				// 不下，所以"断行再试一次"就是个死循环。我们让它单独占一
				// 行，溢出一列，因为在两个坏选项里，丢掉用户的文字是更坏
				// 的那个——溢出的字形看得见、查得出，丢掉的字形两样都不是。
				//
				// 这里把 w 设成超过 n，而不是当场刷出去，正是为了不让末尾
				// 多出一个空行：刷这件事是懒的，发生在下一个 rune 上，而且
				// 只在真有下一个 rune 的时候才发生。
				cur.WriteString(s[i : i+size])
				w = rw
				i += size
				continue
			}
			lines = append(lines, end())
			start()
			continue // 拿这同一个 rune 对着新起的一行再试一次
		}
		cur.WriteString(s[i : i+size])
		w += rw
		i += size
	}
	// 尾巴总是要追加上去的，哪怕它是空的：wrapCols("") 是一个空行，不是零
	// 行，这样画框的调用方才有一行可用。循环只在装不下的时候才刷，所以这一
	// 下不会给正好停在折行点上的输入硬安一个多余的空行。
	return append(lines, end())
}
