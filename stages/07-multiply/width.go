// 阶段 06——显示宽度。
//
// 有三个数经常被人当成同一个，而终端只认其中一个：
//
//	len("你好")                     == 6   字节
//	utf8.RuneCountInString("你好")  == 2   rune
//	dispWidth("你好")               == 4   **列**  ← 只有它决定排版
//
// 前两个都不是列。这件事第一次咬到你，通常是有人把一个中文文件名粘进你排
// 得漂漂亮亮的 `%-20s` 表格，整张表当场从中间错开——`%-20s` 补的是二十个
// **字节**，所以六个汉字的名字（18 字节，12 列）根本不会被补齐，下一列提
// 前八格就开始了。别的行看着都还好好的，所以这个 bug 读起来像"终端坏了"，
// 而不像"我的格式化动词数错了东西"。
//
// 同一个文件还得扛住 ANSI 转义序列，因为 TUI 要量的字符串通常已经上过色
// 了。"\x1b[31mred\x1b[0m" 是 12 字节、3 列；照字节量，表里每一个带颜色的
// 格子都会宽出九格。所以这里每个函数走字符串，用的都是认得转义序列的扫描
// 器，而不是直接 range。
//
// 全是标准库。这件事有现成的好第三方包（go-runewidth）；自己写一遍的意义
// 在于，等你的表错开的时候，你知道是这三个数里的哪一个出了岔子。
package main

import (
	"strings"
	"unicode"
	"unicode/utf8"
)

const (
	esc      = 0x1b
	sgrReset = "\x1b[0m"
)

// ---------------------------------------------------------------------------
// runeWidth
// ---------------------------------------------------------------------------

// runeWidth 返回一个 rune 占终端几列：0、1 或 2。
//
// 控制字符一律算 0。这是有意的选择，而且它有个很扎人的角：**制表符算
// 零**。制表符没有宽度，它有的是一个**目的地**——它的效果取决于光标当前在
// 第几列，而只看一个 rune 的纯函数不可能知道这个。猜 8 吧，只要调用方不是
// 正好停在 8 的倍数上就错了；猜 1 则永远是错的。调用方必须先把制表符展开
// 再来量。换行和回车是 0，理由一样：它们是光标移动，不是墨迹——这也意味着
// 对多行字符串求 dispWidth 毫无意义。先按 "\n" 切开，或者交给 wrapCols，
// 它自己会在那儿断行。
func runeWidth(r rune) int {
	// 先走快路径：TUI 要量的东西几乎全是可打印 ASCII，为了得出 'a' 宽一列
	// 而去二分一张 100 条的表，未免太亏。
	if r < 0x7f {
		if r < 0x20 {
			return 0 // C0 控制字符，\t 和 \n 都在里面——见上
		}
		return 1
	}
	if r < 0xa0 {
		return 0 // DEL（0x7f）和 C1 控制块
	}
	if isZeroWidth(r) {
		return 0
	}
	if inRanges(wideRanges, r) {
		return 2
	}
	// 没被认领的一律算一列。这里面包括 East Asian **Ambiguous** 那批字符——
	// 希腊字母、西里尔字母、框线字符、"…"、"±"——它们在 CJK locale 下是 2
	// 列，在别处是 1 列。我们永远答 1：另一条路是量的时候去读 LANG，而让布
	// 局的形状取决于环境变量，比框子偶尔窄一列要糟得多。
	return 1
}

// isZeroWidth 管的是那些不占自己的列的字符——它们附着在前一个字符上，或者
// 给前一个字符做标注。
//
// 它必须跑在宽字符表**前面**，不能在后面。U+3099 和 U+309A——那两个组合用
// 的假名浊音符号——落在 Katakana 块里，不然就会被量成 2。它们是叠在前面那
// 个假名上的。它们是 0。
func isZeroWidth(r rune) bool {
	switch {
	case r >= 0x200b && r <= 0x200f:
		// ZWSP、ZWNJ、ZWJ（U+200D）、LRM、RLM。ZWJ 是被这个区间顺手扫进来
		// 的，没有单独判——为什么把它归零是必要的、又远远不够，见 wideRanges
		// 上那段关于 emoji 的注释。
		return true
	case r == 0xfeff:
		return true // BOM / 零宽不换行空格
	}
	// Mn = 非间距记号（"é" 里那个重音符），Me = 包围记号。
	// Mc——**带间距**的组合记号，天城文这类文字在用——是故意没列进来的：那
	// 些确实会推进光标。
	return unicode.Is(unicode.Mn, r) || unicode.Is(unicode.Me, r)
}

// ---------------------------------------------------------------------------
// 宽字符表
// ---------------------------------------------------------------------------

type wrange struct{ lo, hi rune }

// inRanges 在一张排好序、互不重叠的区间表上做二分。
//
// 最直白的写法是一串 `if r >= x && r <= y`，而且它一直挺好用——直到这张表
// 有了一百条，还要跑在重绘的每一帧的每一个 rune 上：七次比较，而不是一百
// 次。前置条件——已排序、不相交——这里不检查，因为检查比搜索本身还贵；它
// 在测试套件里断言一次，而那正是给常量的不变式安家的地方。
func inRanges(t []wrange, r rune) bool {
	lo, hi := 0, len(t)-1
	for lo <= hi {
		mid := int(uint(lo+hi) >> 1)
		switch {
		case r < t[mid].lo:
			hi = mid - 1
		case r > t[mid].hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

